# STEP 1: Train & Save the Industrial OCR Model
# (Based on your provided CNN architecture)
# ==========================================

def train_and_save_model(model_path="industry_ocr_model.keras"):
    print("[INFO] Loading dataset and training CNN model...")
    (x_train, y_train), (x_test, y_test) = mnist.load_data()

    # Normalization & Reshaping
    x_train = (x_train / 255.0).reshape(-1, 28, 28, 1)
    x_test = (x_test / 255.0).reshape(-1, 28, 28, 1)

    # Building CNN matching your design
    model = models.Sequential([
        layers.Conv2D(16, (3, 3), activation="relu", input_shape=(28, 28, 1)),
        layers.MaxPooling2D((2, 2)),
        layers.Conv2D(32, (3, 3), activation="relu"),
        layers.MaxPooling2D((2, 2)),
        layers.Flatten(),
        layers.Dense(64, activation="relu"),
        layers.Dense(10, activation="softmax")
    ])

    model.compile(optimizer="adam", loss="sparse_categorical_crossentropy", metrics=["accuracy"])
    model.fit(x_train, y_train, epochs=5, validation_data=(x_test, y_test))

    # Save trained model for edge deployment (AGVs / Microcontrollers)
    model.save(model_path)
    print(f"[INFO] Model successfully saved to '{model_path}'.\n")
    return model

# ==========================================
# STEP 2: Synthetic Industrial Serial Tag Generator
# (Simulates an AGV/AMR camera capturing a tag on a container)
# ==========================================

def generate_mock_asset_tag(digits_indices=[0, 25, 100, 999]):
    """
    Stitches multiple MNIST test images together to simulate
    a multi-digit asset tracking code (e.g., container ID / serial number).
    """
    (_, _), (x_test, y_test) = mnist.load_data()

    selected_images = [x_test[idx] for idx in digits_indices]
    actual_labels = [y_test[idx] for idx in digits_indices]

    # Concatenate horizontally to form a continuous serial plate
    asset_tag_image = np.hstack(selected_images)

    # Add artificial padding/border to mimic a physical label
    asset_tag_image = cv2.copyMakeBorder(
        asset_tag_image, 10, 10, 10, 10, cv2.BORDER_CONSTANT, value=0
    )

    expected_code = "".join(map(str, actual_labels))
    return asset_tag_image, expected_code

# ==========================================
# STEP 3: Image Segmentation Pipeline
# (Crops individual digits from the scanned label)
# ==========================================

def segment_digits_from_tag(tag_image):
    """
    Finds bounding boxes around digits, crops them, and reshapes to 28x28.
    """
    # Thresholding to isolate digit contours
    _, thresh = cv2.threshold(tag_image, 50, 255, cv2.THRESH_BINARY)

    # Find contours (individual character regions)
    contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    bounding_boxes = []
    for c in contours:
        x, y, w, h = cv2.boundingRect(c)
        if w > 5 and h > 5:  # Filter out minor noise
            bounding_boxes.append((x, y, w, h))

    # Sort bounding boxes left-to-right (chronological digit order)
    bounding_boxes = sorted(bounding_boxes, key=lambda b: b[0])

    digit_images = []
    for (x, y, w, h) in bounding_boxes:
        # Extract individual digit region
        digit_crop = tag_image[y:y+h, x:x+w]

        # Resize to 28x28 standard MNIST format with zero-padding
        square_crop = cv2.resize(digit_crop, (20, 20))
        padded_digit = np.pad(square_crop, ((4, 4), (4, 4)), mode='constant', constant_values=0)

        digit_images.append(padded_digit)

    return digit_images, bounding_boxes

# ==========================================
# STEP 4: End-to-End Asset Scanning & ERP Logging
# ==========================================

def scan_and_log_asset(tag_image, model, location_id="WAREHOUSE_BAY_3"):
    """
    Processes the scanned image, predicts the serial number, and logs to ERP system.
    """
    digit_crops, _ = segment_digits_from_tag(tag_image)
    predicted_serial = ""

    for digit_crop in digit_crops:
        # Normalize and reshape for model input (1, 28, 28, 1)
        input_tensor = (digit_crop / 255.0).reshape(1, 28, 28, 1)
        prediction = model.predict(input_tensor, verbose=0)
        predicted_digit = np.argmax(prediction)
        predicted_serial += str(predicted_digit)

    # Generate JSON log entry for Smart Factory ERP / Supply Chain Database
    log_entry = {
        "timestamp": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        "location": location_id,
        "scanned_serial_number": predicted_serial,
        "status": "VERIFIED_INVENTORY"
    }

    return predicted_serial, log_entry

